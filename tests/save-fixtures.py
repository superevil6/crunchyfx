#!/usr/bin/env python3
"""Read make-fixtures.js's dumped FIXTURE lines on stdin and write tests/fixtures/ (see make-fixtures.js)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fixtures")
os.makedirs(OUT, exist_ok=True)
got = {}
for line in sys.stdin:
    if not line.startswith("FIXTURE "):
        continue
    _, name, payload = line.rstrip("\n").split(" ", 2)
    got[name] = json.loads(payload)
if "error" in got or "done" not in got:
    sys.exit("fixtures failed: " + str(got.get("error", "no done line")))
# the project file exactly as Save project wrote it, and the rest as one JS file the suites load
with open(os.path.join(OUT, "v1.1-project.crunchysfx"), "w", encoding="utf-8") as fh:
    fh.write(got["project"]["file"])
with open(os.path.join(OUT, "v1.1.js"), "w", encoding="utf-8") as fh:
    fh.write("// GENERATED by tests/make-fixtures.js on CrunchySFX v1.1 (HEAD 5e457cc): never edit by hand.\n")
    fh.write("window.SFX_V11 = " + json.dumps({k: got[k] for k in ("localStorage", "project", "links", "done")}, ensure_ascii=True, indent=1) + ";\n")
print("wrote", OUT, sorted(got))
